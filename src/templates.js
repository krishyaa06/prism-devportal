// Golden-path templates + real Kubernetes manifest generation.
export const TEMPLATES = {
  "node-api": { label: "Node.js REST API", lang: "TypeScript", port: 8080, cpu: 250, mem: 256, replicas: 3, files: ["src/server.ts", "src/routes/health.ts", "Dockerfile", "openapi.yaml", "catalog-info.yaml"] },
  "react-web": { label: "React web app", lang: "TypeScript", port: 3000, cpu: 150, mem: 192, replicas: 2, files: ["src/App.tsx", "vite.config.ts", "Dockerfile", "nginx.conf", "catalog-info.yaml"] },
  "go-worker": { label: "Go queue worker", lang: "Go", port: 9090, cpu: 400, mem: 384, replicas: 2, files: ["main.go", "worker/consumer.go", "Dockerfile", "catalog-info.yaml"] },
  "python-ml": { label: "Python ML service", lang: "Python", port: 8000, cpu: 800, mem: 1024, replicas: 2, files: ["app/main.py", "app/model.py", "requirements.txt", "Dockerfile", "catalog-info.yaml"] },
};
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-|-$/g, "").slice(0, 50);
export function validateName(name) { const s = slug(name); if (!s || s !== name) throw new Error(`Service name must be lowercase DNS-1123 (got "${name}", try "${s || "my-service"}")`); return s; }

/** Kubernetes manifests (Deployment + Service + HPA + PDB) as YAML. */
export function manifests({ name, template = "node-api", version = "1.0.0", team = "platform", env = "dev", image }) {
  const t = TEMPLATES[template]; if (!t) throw new Error(`Unknown template "${template}" (${Object.keys(TEMPLATES).join(", ")})`);
  validateName(name);
  const img = image || `ghcr.io/prism/${name}:${version}`;
  const labels = `app.kubernetes.io/name: ${name}\n      app.kubernetes.io/version: "${version}"\n      app.kubernetes.io/part-of: prism\n      prism.dev/team: ${team}`;
  return `# Generated by Prism DevPortal · template ${template} · env ${env}
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${name}
  namespace: ${env}
  labels:
    app.kubernetes.io/name: ${name}
spec:
  replicas: ${t.replicas}
  revisionHistoryLimit: 10
  strategy:
    type: RollingUpdate
    rollingUpdate: { maxSurge: 1, maxUnavailable: 0 }
  selector:
    matchLabels:
      app.kubernetes.io/name: ${name}
  template:
    metadata:
      labels:
      ${labels}
    spec:
      containers:
        - name: ${name}
          image: ${img}
          ports: [{ containerPort: ${t.port} }]
          resources:
            requests: { cpu: ${t.cpu}m, memory: ${t.mem}Mi }
            limits: { cpu: ${t.cpu * 2}m, memory: ${t.mem * 2}Mi }
          readinessProbe: { httpGet: { path: /healthz, port: ${t.port} }, periodSeconds: 5 }
          livenessProbe: { httpGet: { path: /livez, port: ${t.port} }, initialDelaySeconds: 10 }
---
apiVersion: v1
kind: Service
metadata:
  name: ${name}
  namespace: ${env}
spec:
  selector:
    app.kubernetes.io/name: ${name}
  ports: [{ port: 80, targetPort: ${t.port} }]
---
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: ${name}
  namespace: ${env}
spec:
  scaleTargetRef: { apiVersion: apps/v1, kind: Deployment, name: ${name} }
  minReplicas: ${t.replicas}
  maxReplicas: ${t.replicas * 4}
  metrics:
    - type: Resource
      resource: { name: cpu, target: { type: Utilization, averageUtilization: 70 } }
---
apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: ${name}
  namespace: ${env}
spec:
  minAvailable: ${Math.max(1, t.replicas - 1)}
  selector:
    matchLabels:
      app.kubernetes.io/name: ${name}
`;
}
/** Backstage-compatible catalog-info.yaml */
export function catalogInfo({ name, team = "platform", template = "node-api", description = "" }) {
  return `apiVersion: backstage.io/v1alpha1
kind: Component
metadata:
  name: ${name}
  description: ${description || TEMPLATES[template].label}
  annotations:
    github.com/project-slug: prism/${name}
    prism.dev/template: ${template}
spec:
  type: service
  lifecycle: production
  owner: team-${team}
`;
}
